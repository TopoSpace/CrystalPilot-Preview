"""interpret_peaks without a metal: density tiers instead of M-O windows.

Before T1.2 every structure went through the metal-coordination lens.
`metals` was "is_metal(el) or Z >= 17", so a chloride salt was solved as
if the Cl were a metal centre and every peak 1.8-2.6 A from it became an
O; a pure organic got NO oxygen at all (no metal -> no M-O window -> all
C). Both are the same mistake: reading an organic through MOF chemistry.

The cases below are built from synthetic structures of four different
types (nothing here is tuned to one crystal): the peak list handed to
the tool is a REAL peak search of the structure's own Fc density, and
the tiers are read from real integrated densities in 0.7 A spheres.
"""
from __future__ import annotations

import math

import pytest
from cctbx import crystal, maptbx, xray
from cctbx.array_family import flex

from crystalpilot.core.dataset import CompositionHint, ReflectionDataset
from crystalpilot.pipeline.session import SolveSession
from crystalpilot.tools import solution_tools as st
from crystalpilot.tools.base import ToolContext
from crystalpilot.tools.model_tools import InterpretPeaks


class _Store:
    def emit(self, *a, **k):
        return None

    def record(self, *a, **k):
        return None

    def log(self, *a, **k):
        return None


def _structure(cell, sg, atoms):
    cs = crystal.symmetry(unit_cell=cell, space_group_symbol=sg)
    xs = xray.structure(crystal_symmetry=cs)
    uc = cs.unit_cell()
    for label, el, cart in atoms:
        xs.add_scatterer(xray.scatterer(
            label=label, site=uc.fractionalize(cart), scattering_type=el,
            u=0.025))
    xs.scattering_type_registry(table="it1992")
    return xs


def _solved_session(xs, elements: dict[str, float], z: float,
                    d_min: float = 0.85) -> SolveSession:
    """A session that looks exactly like one a solver just left behind.

    The peak list is a real peak search of the structure's own density
    and the per-peak densities are real 0.7 A sphere integrals - the same
    two numbers solve_charge_flipping now stores in cf_info.
    """
    cs = xs.crystal_symmetry()
    f_calc = xs.structure_factors(d_min=d_min).f_calc()
    fo_sq = f_calc.intensities().customized_copy(
        sigmas=flex.double(f_calc.size(), 1.0)
    ).set_observation_type_xray_intensity()
    fft_map = f_calc.fft_map(symmetry_flags=maptbx.use_space_group_symmetry)
    fft_map.apply_volume_scaling()
    peaks = fft_map.peak_search(
        maptbx.peak_search_parameters(
            interpolate=True, min_distance_sym_equiv=0.8,
            min_cross_distance=0.9,
            max_clusters=int(xs.scatterers().size() * 2) + 8),
        verify_symmetry=False).all()
    sites = list(peaks.sites())
    heights = list(peaks.heights())
    integrated = st._peak_density(fft_map.real_map_unpadded(),
                                  cs.unit_cell(), sites)
    ses = SolveSession(dataset=ReflectionDataset(
        intensities=None, wavelength=0.71073,
        composition=CompositionHint(elements=dict(elements), z=z,
                                    source="unit test")))
    ses.symmetry = cs
    ses.fo_sq = fo_sq
    ses.merge_info = {"d_min": round(fo_sq.d_min(), 3),
                      "completeness": round(
                          fo_sq.completeness(d_max=float("inf")), 3)}
    ses.cf_info = {
        "d_min": d_min, "peak_sites": sites, "peak_heights": heights,
        **({"peak_integrated_density": [round(v, 3) for v in integrated],
            "peak_density_radius_A": st.PEAK_DENSITY_RADIUS_A,
            "peak_density_units": "electrons (volume-scaled map)"}
           if integrated else {})}
    return ses


def _run(ses, **params):
    r = InterpretPeaks().run(ToolContext(store=_Store(), session=ses),
                             **params)
    assert r.ok, r.error
    return r.summary


def _rows(summary):
    return {row["atom"]: row for row in summary["element_assignment"]}


