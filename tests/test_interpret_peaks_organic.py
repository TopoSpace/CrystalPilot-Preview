def test_heights_only_peak_list_says_so():
    ses = _solved_session(_benzoic_acid_dimer(), {"C": 7, "H": 6, "O": 2},
                          z=2)
    for key in ("peak_integrated_density", "peak_density_units",
                "peak_density_radius_A"):
        ses.cf_info.pop(key, None)
    s = _run(ses)
    assert s["density_measure"] == "peak HEIGHT only"
    assert "peaks.json" in s["density_note"]
    assert s["ranked_by"] == "peak height"
    # the tiers still work on heights - they are ratios either way
    assert s["element_counts"].get("O") == 4, s


def test_a_site_in_the_O_tier_beyond_the_O_allowance_says_which_fact_won():
    """When the composition's O count runs out before the density tier
    does, the site that missed out must say the COMPOSITION decided it -
    otherwise the agent reads a chemistry claim into a bookkeeping cap."""
    ses = _solved_session(_benzoic_acid_dimer(), {"C": 7, "H": 6, "O": 2},
                          z=2)
    ses.dataset.composition.elements = {"C": 8, "H": 6, "O": 1}
    s = _run(ses)
    assert s["element_counts"]["O"] == 2         # 1 per formula unit, Z=2
    squeezed = [r for r in s["element_assignment"]
                if r["element"] == "C" and "allowance" in r["reason"]]
    assert squeezed, [r["reason"] for r in s["element_assignment"][:5]]
    assert all(r["element_uncertain"] for r in squeezed)
    assert "could be the O" in squeezed[0]["reason"]


def test_a_site_below_the_H_C_line_is_not_passed_off_as_a_carbon():
    """A half-occupied site (or map noise) carries far too few electrons
    for a full-weight light atom; the tier says so instead of letting it
    ride as an ordinary C. The line is the H/C midpoint - Z 1 vs Z 6 -
    so it holds for any element, not just this fixture."""
    xs = _benzoic_acid_dimer()
    xs.scatterers()[3].occupancy = 0.15
    ses = _solved_session(xs, {"C": 7, "H": 6, "O": 2}, z=2)
    s = _run(ses)
    weak = [r for r in s["element_assignment"]
            if r.get("below_light_atom_tier")]
    assert weak, [r["density_ratio"] for r in s["element_assignment"]]
    for r in weak:
        assert r["element_confidence"] == "low"
        assert r["element_uncertain"] is True
        assert "H/C line" in r["reason"]
        assert r["density_ratio"] < 0.41
    # and a full-weight carbon is NOT flagged
    assert any(not r.get("below_light_atom_tier")
               for r in s["element_assignment"] if r["element"] == "C")


def test_unknown_composition_keeps_every_light_label_uncertain():
    ses = _solved_session(_benzoic_acid_dimer(), {"C": 7, "H": 6, "O": 2},
                          z=2)
    ses.dataset.composition = None
    s = _run(ses)
    assert s["branch"] == "metal_free_density_tier"
    assert s["composition_known"] is False
    rows = _rows(s)
    assert rows and all(r["element_uncertain"] for r in rows.values())
    assert all(r["element_confidence"] == "low" for r in rows.values())


