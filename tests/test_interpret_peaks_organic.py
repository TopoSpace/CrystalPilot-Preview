def _benzoic_acid_dimer():
    """The R2,2(8) carboxylic-acid dimer, both halves written out in P1.

    Ideal geometry: 1.39 A aromatic ring bonds, a 1.48 A ring-to-carboxyl
    bond, a 1.23 A C=O and a 1.31 A C-OH, the second molecule generated by
    inverting the first through the point between the two carboxyls (the
    classic hydrogen-bonded dimer, here at O...O 2.99 A).
    """
    mol = []
    r, cx0, cy = 1.39, 4.0, 5.0
    for k in range(6):
        a = math.radians(60 * k)
        mol.append(("C", (cx0 + r * math.cos(a), cy + r * math.sin(a), 5.0)))
    cx = cx0 + r + 1.48
    mol.append(("C", (cx, cy, 5.0)))
    mol.append(("O", (cx + 1.23 * math.cos(math.radians(60)),
                      cy + 1.23 * math.sin(math.radians(60)), 5.0)))
    mol.append(("O", (cx + 1.31 * math.cos(math.radians(-60)),
                      cy + 1.31 * math.sin(math.radians(-60)), 5.0)))
    centre = (9.0, 4.965, 5.0)
    atoms, n = [], {"C": 0, "O": 0}
    for half in (1, -1):
        for el, cart in mol:
            n[el] += 1
            p = cart if half == 1 else tuple(2 * c - x
                                             for c, x in zip(centre, cart))
            atoms.append((f"{el}{n[el]}", el, p))
    return _structure((17.0, 14.0, 12.0, 90, 90, 90), "P 1", atoms)


def _dbu_hcl_like():
    """A bicyclic amidinium cation plus a free chloride.

    9 skeletal carbons (the tool must not type the two nitrogens), one
    chloride with no covalent partner - the DBU.HCl motif. Chemistry, not
    a copy of any particular crystal.
    """
    atoms = []
    # amidinium head: a short delocalised C-N pair drawn as skeleton atoms
    ring = [(4.20, 4.00, 4.00), (5.60, 4.35, 4.20), (6.35, 3.20, 4.70),
            (5.60, 1.95, 4.30), (4.20, 2.05, 4.55), (3.50, 3.15, 5.05),
            (7.70, 3.30, 4.10), (8.30, 4.60, 4.60), (7.35, 5.55, 5.20)]
    for k, cart in enumerate(ring):
        atoms.append((f"C{k + 1}", "C", cart))
    atoms.append(("CL1", "Cl", (1.20, 7.60, 8.40)))
    return _structure((11.5, 12.5, 13.5, 90, 103.0, 90), "P 1", atoms)


def _cu_paddlewheel():
    """Cu2(O2CR)4 fragment: the metal branch must be untouched by T1.2."""
    atoms = [("CU1", "Cu", (5.00, 5.00, 4.70)),
             ("CU2", "Cu", (5.00, 5.00, 7.30))]
    for k, (dx, dy) in enumerate(((1.97, 0.0), (-1.97, 0.0),
                                  (0.0, 1.97), (0.0, -1.97))):
        atoms.append((f"O{2 * k + 1}", "O", (5.0 + dx, 5.0 + dy, 4.85)))
        atoms.append((f"O{2 * k + 2}", "O", (5.0 + dx, 5.0 + dy, 7.15)))
        atoms.append((f"C{k + 1}", "C",
                      (5.0 + dx * 1.42, 5.0 + dy * 1.42, 6.00)))
    return _structure((14.0, 14.0, 15.0, 90, 90, 90), "P 1", atoms)


def _thiophene_like():
    """2-acetylthiophene: S is an anchor and a ring member, never a metal.

    Ring from the microwave geometry (S-C 1.714, C-S-C 92.2 deg, C2-C3
    1.370, C3-C4 1.423), acetyl group at C2 with a 1.22 A C=O.
    """
    o = (4.0, 3.0, 4.0)

    def at(x, y):
        return (o[0] + x, o[1] + y, o[2])

    half = math.radians(46.1)
    c2 = (1.714 * math.sin(half), 1.714 * math.cos(half))
    c5 = (-c2[0], c2[1])
    # S-C2-C3 111.5 deg, C2-C3 1.370: rotate the C2->S bond into place
    ux, uy = (-c2[0] / 1.714, -c2[1] / 1.714)
    th = math.radians(-111.5)
    dx = ux * math.cos(th) - uy * math.sin(th)
    dy = ux * math.sin(th) + uy * math.cos(th)
    c3 = (c2[0] + 1.370 * dx, c2[1] + 1.370 * dy)
    c4 = (-c3[0], c3[1])
    # acetyl on C2, pointing away from the ring centre
    cen = ((0 + c2[0] + c3[0] + c4[0] + c5[0]) / 5,
           (0 + c2[1] + c3[1] + c4[1] + c5[1]) / 5)
    vx, vy = c2[0] - cen[0], c2[1] - cen[1]
    vn = math.hypot(vx, vy)
    vx, vy = vx / vn, vy / vn
    ca = (c2[0] + 1.47 * vx, c2[1] + 1.47 * vy)
    bx, by = -vx, -vy                       # ca -> c2
    for ang, dist, out in ((-120.0, 1.22, "o"), (120.0, 1.50, "me")):
        t = math.radians(ang)
        px = bx * math.cos(t) - by * math.sin(t)
        py = bx * math.sin(t) + by * math.cos(t)
        if out == "o":
            oc = (ca[0] + dist * px, ca[1] + dist * py)
        else:
            me = (ca[0] + dist * px, ca[1] + dist * py)
    atoms = [("S1", "S", at(0.0, 0.0)),
             ("C1", "C", at(*c2)), ("C2", "C", at(*c3)),
             ("C3", "C", at(*c4)), ("C4", "C", at(*c5)),
             ("C5", "C", at(*ca)), ("O1", "O", at(*oc)),
             ("C6", "C", at(*me))]
    return _structure((12.0, 13.0, 10.5, 90, 95.0, 90), "P 1", atoms)


