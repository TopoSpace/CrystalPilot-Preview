class TestBenzoicAcidDimer:

    def test_takes_the_metal_free_branch(self, summary_benzoic):
        assert summary_benzoic["branch"] == "metal_free_density_tier"
        assert "0.7 A sphere" in summary_benzoic["density_measure"]
        assert summary_benzoic["density_units"].startswith("electrons")

    def test_oxygen_is_found_by_density_tier(self, summary_benzoic):
        assert summary_benzoic["element_counts"].get("O") == 4, summary_benzoic
        rows = _rows(summary_benzoic)
        for lbl, row in rows.items():
            if row["element"] == "O":
                assert row["density_ratio"] >= 1.15, row
                assert "tier line" in row["reason"]

    def test_carbon_sites_are_never_claimed(self, summary_benzoic):
        rows = _rows(summary_benzoic)
        carbons = [r for r in rows.values() if r["element"] == "C"]
        assert carbons
        assert all(r["element_uncertain"] for r in carbons), carbons
        assert all(r["element_confidence"] in ("low", "medium")
                   for r in carbons)
        assert summary_benzoic["n_element_uncertain"] >= len(carbons)

    def test_nitrogen_budget_is_disclosure_only(self, summary_benzoic):
        nb = summary_benzoic["nitrogen_budget"]
        assert nb["n_assigned"] == 0
        assert nb["n_allowed_per_asu"] == 0.0
        assert "N" not in summary_benzoic["element_counts"]

    def test_chem_hint_reads_the_organic_motifs(self, summary_benzoic):
        motifs = {m["motif"] for m in summary_benzoic["chem_hint"]["motifs"]}
        assert "aromatic_ring" in motifs, summary_benzoic["chem_hint"]
        assert motifs & {"carboxylate", "carboxylic_acid_or_ester"}, motifs
        # every motif has to say WHY, in distances
        for m in summary_benzoic["chem_hint"]["motifs"]:
            assert " A" in m["evidence"], m


