def test_c_and_n_are_never_separable_but_c_and_o_are():
    from crystalpilot.tools.peak_chemistry import _competitors
    assert _competitors("C", ["C", "N", "O"]) == ["N"]
    assert _competitors("O", ["C", "N", "O"]) == ["N"]
    assert _competitors("O", ["C", "O"]) == []
    # S and Cl are 6 % apart in Z - not separable either
    assert _competitors("Cl", ["C", "S", "Cl"]) == ["S"]
