class TestOrganicChlorideSalt:

    def test_chloride_does_not_make_it_a_metal_case(self, summary_chloride):
        assert summary_chloride["branch"] == "metal_free_density_tier"
        assert summary_chloride["element_counts"].get("Cl") == 1, summary_chloride
        rows = _rows(summary_chloride)
        cl = [r for r in rows.values() if r["element"] == "Cl"][0]
        assert cl["density_ratio"] >= 1.68, cl        # the C/Cl tier line
        assert cl["element_confidence"] == "high"
        assert cl["element_uncertain"] is False

    def test_no_oxygen_is_invented_around_the_chloride(self, summary_chloride):
        # the old branch called every peak 1.8-2.6 A from the "metal" an O
        assert "O" not in summary_chloride["element_counts"], summary_chloride

    def test_the_two_nitrogens_are_disclosed_not_placed(self, summary_chloride):
        nb = summary_chloride["nitrogen_budget"]
        assert nb["n_allowed_per_asu"] == 2.0
        assert nb["n_assigned"] == 0
        assert "17 %" in nb["note"]
        assert "N" not in summary_chloride["element_counts"]
        rows = _rows(summary_chloride)
        carbons = [r for r in rows.values() if r["element"] == "C"]
        assert all(r["element_uncertain"] for r in carbons)
        assert all(r["element_confidence"] == "low" for r in carbons), carbons

    def test_chloride_is_recognised_as_an_unbound_ion(self, summary_chloride):
        motifs = {m["motif"] for m in summary_chloride["chem_hint"]["motifs"]}
        assert "halide_ion" in motifs, summary_chloride["chem_hint"]


